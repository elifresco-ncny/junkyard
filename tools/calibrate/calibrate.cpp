// junkyard_calibrate drive | broken | alias
//   drive  : fits the fixed Drive level-match curves on the synthetic corpus -> src/dsp/DriveCalTable.h + docs/DRIVE_CAL.md
//   broken : fits Broken mode's fixed level trim table                       -> src/dsp/BrokenTrimTable.h
//   alias  : prints the alias level of the Drive stage (5 kHz sine, -6 dBFS, Drive 100 %)
// Deterministic (fixed seeds). Re-run after ANY change to DriveStage or the Broken codec path; the guard test fails otherwise.
